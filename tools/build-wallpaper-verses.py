#!/usr/bin/env python3
"""
Quran Maar - bundles the daily-wallpaper verses for offline use.

Reads the Arabic (Uthmani Hafs) and English (Saheeh International) text of each
curated "ayah of the day" verse straight from the project's own surah pages
(surah/<n>-<slug>/index.html, themselves generated by tools/build-seo.py from
fawazahmed0/quran-api) and writes
    android/app/src/main/assets/wallpaper/verses.json

Nothing is typed in or invented here: every verse is copied from those pages and
the script stops with an error if a verse is missing, empty, or mis-numbered.

Usage (repo root):   python3 tools/build-wallpaper-verses.py
"""
import glob, html, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Same list, same order as DAILY_AYAH_REFS in app.js and REFS in WallpaperStore.java
REFS = ["2:255","2:286","2:152","2:153","2:186","2:45","2:156","2:201","3:8","3:26","3:139","3:159","3:173","3:200",
        "4:103","5:8","6:162","7:23","7:56","8:46","9:51","10:62","11:88","12:87","13:28","14:7","15:9","16:90","16:128",
        "17:23","17:80","18:10","20:114","21:87","23:118","24:35","25:63","28:24","29:69","31:17","33:41","33:56",
        "39:10","39:53","40:60","41:34","42:36","49:13","51:56","55:13","57:4","59:22","59:23","64:11","65:2","65:3",
        "93:3","94:5","94:6","112:1"]

# English surah names, taken from tools/build-seo.py so both agree
seo = open(os.path.join(ROOT, 'tools', 'build-seo.py'), encoding='utf-8').read()
m = re.search(r'NAMES\s*=\s*\[(.*?)\]', seo, re.S)
NAMES = re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(1))
assert len(NAMES) == 114, len(NAMES)

LI = re.compile(r'<li id="ayah-(\d+)">.*?<p class="ar"[^>]*>(.*?)</p><p class="en">(.*?)</p></li>', re.S)
TITLE = re.compile(r'<p class="ar-title"[^>]*>(.*?)</p>', re.S)

out, pages = {}, {}
for ref in REFS:
    s, a = (int(x) for x in ref.split(':'))
    if s not in pages:
        hits = glob.glob(os.path.join(ROOT, 'surah', f'{s}-*', 'index.html'))
        if len(hits) != 1:
            sys.exit(f'surah {s}: expected one page, found {hits}')
        txt = open(hits[0], encoding='utf-8').read()
        verses = {int(n): (html.unescape(ar).strip(), html.unescape(en).strip()) for n, ar, en in LI.findall(txt)}
        if not verses or sorted(verses) != list(range(1, len(verses) + 1)):
            sys.exit(f'surah {s}: verse numbering is not 1..N')
        t = TITLE.search(txt)
        pages[s] = (verses, html.unescape(t.group(1)).strip() if t else '')
    verses, ar_title = pages[s]
    if a not in verses:
        sys.exit(f'{ref}: verse not found on the surah page')
    ar, en = verses[a]
    if not ar or not en:
        sys.exit(f'{ref}: empty Arabic or English text')
    out[ref] = {'n': s, 'a': a, 'se': NAMES[s - 1], 'sa': ar_title, 'ar': ar, 'en': en}

dest = os.path.join(ROOT, 'android', 'app', 'src', 'main', 'assets', 'wallpaper', 'verses.json')
os.makedirs(os.path.dirname(dest), exist_ok=True)
with open(dest, 'w', encoding='utf-8') as f:
    json.dump(out, f, ensure_ascii=False, indent=0, separators=(',', ':'))
print(f'wrote {len(out)} verses -> {os.path.relpath(dest, ROOT)} ({os.path.getsize(dest)//1024} KB)')
